//! Generate/check committed JSON Schema for daemon-owned public responses.

use dockermap_core::schema_baseline::{daemon_schema_documents, DAEMON_SCHEMA_NAMES};
use serde_json::Value;
use std::{env, fs, path::PathBuf, process::ExitCode};

fn output_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/contracts/generated/rust")
}

fn typescript_output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join("packages/contracts/src/rustSchemas.ts")
}

fn artifact_name(component_name: &str) -> String {
    let mut output = String::new();
    for (index, character) in component_name.char_indices() {
        if character.is_ascii_uppercase() {
            if index > 0 {
                output.push('-');
            }
            output.push(character.to_ascii_lowercase());
        } else {
            output.push(character);
        }
    }
    output
}

fn render() -> Result<Vec<(String, String)>, String> {
    DAEMON_SCHEMA_NAMES
        .into_iter()
        .zip(daemon_schema_documents())
        .map(|(name, schema)| {
            let content = serde_json::to_string_pretty(&schema)
                .map_err(|error| format!("failed to serialize {name} schema: {error}"))?;
            Ok((
                format!("{}.schema.json", artifact_name(name)),
                format!("{content}\n"),
            ))
        })
        .collect()
}

fn render_typescript() -> Result<String, String> {
    let mut output = String::from(
        "// Generated by `npm run generate:contracts`; do not edit.\n\
         // Rust Serde/Schemars response models are the schema authority.\n\n\
         export const RUST_RESPONSE_SCHEMAS = {\n",
    );
    for (name, schema) in DAEMON_SCHEMA_NAMES
        .into_iter()
        .zip(daemon_schema_documents())
    {
        let content = serde_json::to_string_pretty(&schema)
            .map_err(|error| format!("failed to serialize {name} TypeScript schema: {error}"))?;
        output.push_str(&format!("  {name}: {content},\n"));
    }
    output.push_str("} as const;\n\nexport const OPENAPI_RUST_RESPONSE_SCHEMAS = {\n");
    for (name, mut schema) in DAEMON_SCHEMA_NAMES
        .into_iter()
        .zip(daemon_schema_documents())
    {
        // A standalone Schemars document resolves `#/$defs/...` at its own
        // root. Once it is an OpenAPI component, that root is the OpenAPI
        // document, so emit an explicitly rebased component copy. The source
        // schema is still generated by Rust; only its embedding address moves.
        rebase_component_refs(&mut schema, name);
        let content = serde_json::to_string_pretty(&schema)
            .map_err(|error| format!("failed to serialize {name} OpenAPI schema: {error}"))?;
        output.push_str(&format!("  {name}: {content},\n"));
    }
    output.push_str(
        "} as const;\n\nexport type RustResponseSchemaId = keyof typeof RUST_RESPONSE_SCHEMAS;\n",
    );
    Ok(output)
}

fn rebase_component_refs(value: &mut Value, component_name: &str) {
    match value {
        Value::Array(values) => values
            .iter_mut()
            .for_each(|child| rebase_component_refs(child, component_name)),
        Value::Object(object) => {
            if let Some(Value::String(reference)) = object.get_mut("$ref") {
                if let Some(definition) = reference.strip_prefix("#/$defs/") {
                    *reference =
                        format!("#/components/schemas/{component_name}/$defs/{definition}");
                }
            }
            for child in object.values_mut() {
                rebase_component_refs(child, component_name);
            }
        }
        _ => {}
    }
}

fn main() -> ExitCode {
    let check = matches!(env::args().nth(1).as_deref(), Some("--check"));
    if !check && env::args().nth(1).is_some() {
        eprintln!("usage: generate-contract-schemas [--check]");
        return ExitCode::FAILURE;
    }

    let output_dir = output_dir();
    let rendered = match render() {
        Ok(rendered) => rendered,
        Err(error) => {
            eprintln!("{error}");
            return ExitCode::FAILURE;
        }
    };
    let typescript = match render_typescript() {
        Ok(rendered) => rendered,
        Err(error) => {
            eprintln!("{error}");
            return ExitCode::FAILURE;
        }
    };

    if check {
        let mut stale = false;
        let second_render = match render() {
            Ok(rendered) => rendered,
            Err(error) => {
                eprintln!("{error}");
                return ExitCode::FAILURE;
            }
        };
        if rendered != second_render {
            stale = true;
            eprintln!("non-deterministic generated schema output");
        }
        let expected_names = DAEMON_SCHEMA_NAMES
            .iter()
            .map(|name| format!("{}.schema.json", artifact_name(name)))
            .collect::<std::collections::BTreeSet<_>>();
        match fs::read_dir(&output_dir) {
            Ok(entries) => {
                for entry in entries.flatten() {
                    let name = entry.file_name().to_string_lossy().into_owned();
                    if !expected_names.contains(&name) {
                        stale = true;
                        eprintln!("unexpected generated schema: {}", entry.path().display());
                    }
                }
            }
            Err(_) => {
                stale = true;
                eprintln!(
                    "missing generated schema directory: {}",
                    output_dir.display()
                );
            }
        }
        for (name, expected) in rendered {
            let path = output_dir.join(&name);
            match fs::read_to_string(&path) {
                Ok(actual) if actual == expected => {}
                Ok(_) => {
                    stale = true;
                    eprintln!("stale generated schema: {}", path.display());
                }
                Err(_) => {
                    stale = true;
                    eprintln!("missing generated schema: {}", path.display());
                }
            }
        }
        match fs::read_to_string(typescript_output_path()) {
            Ok(actual) if actual == typescript => {}
            Ok(_) => {
                stale = true;
                eprintln!("stale generated TypeScript schema export");
            }
            Err(_) => {
                stale = true;
                eprintln!("missing generated TypeScript schema export");
            }
        }
        return if stale {
            ExitCode::FAILURE
        } else {
            ExitCode::SUCCESS
        };
    }

    if let Err(error) = fs::create_dir_all(&output_dir) {
        eprintln!("failed to create {}: {error}", output_dir.display());
        return ExitCode::FAILURE;
    }
    for (name, content) in rendered {
        let path = output_dir.join(name);
        if let Err(error) = fs::write(&path, content) {
            eprintln!("failed to write {}: {error}", path.display());
            return ExitCode::FAILURE;
        }
    }
    let typescript_output_path = typescript_output_path();
    if let Err(error) = fs::write(&typescript_output_path, typescript) {
        eprintln!(
            "failed to write {}: {error}",
            typescript_output_path.display()
        );
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

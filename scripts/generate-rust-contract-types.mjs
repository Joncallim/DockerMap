#!/usr/bin/env node
/**
 * Emits TypeScript declarations from committed Rust/Schemars schema artifacts.
 * Rust serialization models are the only authority for daemon-facing values.
 */
import { compile } from "json-schema-to-typescript";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const check = process.argv.slice(2).join(" ") === "--check";
if (process.argv.length > 3 && !check) throw new Error("usage: generate-rust-contract-types.mjs [--check]");

const root = resolve(import.meta.dirname, "..");
const schemaDirectory = process.env.DOCKERMAP_RUST_SCHEMA_DIRECTORY ?? resolve(root, "packages/contracts/generated/rust");
const output = process.env.DOCKERMAP_RUST_MODELS_OUTPUT ?? resolve(root, "packages/contracts/src/rustModels.ts");
const roots = [
  ["DockerSnapshot", "docker-snapshot"], ["GraphResponse", "graph-response"],
  ["RuntimeMap", "runtime-map"], ["ComposeScan", "compose-scan"],
  ["ComposeGraph", "compose-graph"], ["ComposeEditPlan", "compose-edit-plan"],
  ["LogsResponse", "logs-response"], ["HealthResponse", "health-response"],
  ["ContainersResponse", "containers-response"], ["ContainerDetailResponse", "container-detail-response"],
  ["ImagesResponse", "images-response"], ["NetworksResponse", "networks-response"],
  ["VolumesResponse", "volumes-response"], ["FindingsResponse", "findings-response"],
  ["ObservedChangeHistoryResponse", "observed-change-history-response"]
];

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === "object") return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stable(value[key])]));
  return value;
}

function mergeDefinition(definitions, name, value) {
  const existing = definitions[name];
  if (existing && JSON.stringify(stable(existing)) !== JSON.stringify(stable(value))) {
    throw new Error(`Rust schema definition ${name} differs between response roots`);
  }
  definitions[name] ??= value;
}

function normalizedRoot(document) {
  const root = structuredClone(document);
  delete root.$schema;
  delete root.$id;
  delete root.title;
  delete root.$defs;
  return root;
}

function reachableDefinitions(root, definitions) {
  const names = new Set();
  const visit = (value) => {
    if (Array.isArray(value)) return value.forEach(visit);
    if (!value || typeof value !== "object") return;
    if (typeof value.$ref === "string" && value.$ref.startsWith("#/$defs/")) {
      const name = value.$ref.slice("#/$defs/".length);
      if (!definitions[name]) throw new Error(`transparent wrapper references missing definition ${name}`);
      if (!names.has(name)) {
        names.add(name);
        visit(definitions[name]);
      }
    }
    Object.values(value).forEach(visit);
  };
  visit(root);
  return Object.fromEntries([...names].sort().map((name) => [name, definitions[name]]));
}

function assertTransparentDetailMatchesRecord(documents) {
  const detail = documents.get("ContainerDetailResponse");
  const snapshot = documents.get("DockerSnapshot");
  const record = snapshot?.$defs?.ContainerRecord;
  if (!detail || !record) throw new Error("missing transparent container detail or record schema");
  const detailRoot = normalizedRoot(detail);
  const canonicalDetail = {
    root: detailRoot,
    definitions: reachableDefinitions(detailRoot, detail.$defs ?? {})
  };
  const canonicalRecord = {
    root: record,
    definitions: reachableDefinitions(record, snapshot.$defs ?? {})
  };
  if (JSON.stringify(stable(canonicalDetail)) !== JSON.stringify(stable(canonicalRecord))) {
    throw new Error("transparent ContainerDetailResponse schema differs from ContainerRecord; refusing declaration alias");
  }
}

async function render() {
  const definitions = {};
  const documents = new Map();
  for (const [name, file] of roots) {
    const document = JSON.parse(await readFile(resolve(schemaDirectory, `${file}.schema.json`), "utf8"));
    documents.set(name, document);
    for (const [definitionName, definition] of Object.entries(document.$defs ?? {})) mergeDefinition(definitions, definitionName, definition);
    const rootDefinition = structuredClone(document);
    delete rootDefinition.$schema;
    delete rootDefinition.$id;
    delete rootDefinition.$defs;
    delete rootDefinition.title;
    mergeDefinition(definitions, name, rootDefinition);
  }
  assertTransparentDetailMatchesRecord(documents);
  // The transparent detail response serializes exactly as ContainerRecord.
  definitions.ContainerDetailResponse = { $ref: "#/$defs/ContainerRecord" };
  const declarations = await compile({
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "RustDaemonModels",
    oneOf: roots.map(([name]) => ({ $ref: `#/$defs/${name}` })),
    $defs: definitions
  }, "RustDaemonModels", {
    bannerComment: "// Generated by `npm run generate:contracts`; do not edit.\n// Rust Serde/Schemars models are the declaration authority.\n",
    format: true,
    style: { singleQuote: true }
  });
  return `${declarations}\n// Rust's transparent route wrapper serializes as the record itself.\nexport type ContainerDetailResponse = ContainerRecord;\n// Stable aliases distinguish the exact daemon shapes from Node-owned API overlays.\nexport type DaemonRuntimeMap = RuntimeMap;\nexport type DaemonRuntimeMapNode = RuntimeMapNode;\nexport type DaemonRuntimeMapEdge = RuntimeMapEdge;\n`;
}

const expected = await render();
if (check) {
  const actual = await readFile(output, "utf8").catch(() => null);
  if (actual !== expected) {
    console.error("stale generated Rust TypeScript declarations; run npm run generate:contracts");
    process.exitCode = 1;
  }
} else {
  await writeFile(output, expected);
}

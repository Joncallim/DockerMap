#!/usr/bin/env node
/**
 * Product-version authority is intentionally dependency-free: it runs before
 * release artifact staging and must not depend on the application dependency
 * graph being installed.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

function validNumericIdentifier(value) {
  return /^(0|[1-9]\d*)$/.test(value);
}

function validDotIdentifiers(value, numericNoLeadingZero) {
  return value.length > 0 && value.split(".").every((identifier) =>
    /^[0-9A-Za-z-]+$/.test(identifier)
      && (!numericNoLeadingZero || !/^\d+$/.test(identifier) || validNumericIdentifier(identifier))
  );
}

// Strict SemVer 2.0.0: numeric identifiers cannot have leading zeroes,
// including numeric prerelease identifiers.
export function isStrictSemver(value) {
  const buildParts = value.split("+");
  if (buildParts.length > 2 || (buildParts.length === 2 && !validDotIdentifiers(buildParts[1], false))) return false;
  const prereleaseSeparator = buildParts[0].indexOf("-");
  const coreAndPrerelease = prereleaseSeparator === -1
    ? [buildParts[0], undefined]
    : [buildParts[0].slice(0, prereleaseSeparator), buildParts[0].slice(prereleaseSeparator + 1)];
  if (coreAndPrerelease[1] !== undefined && !validDotIdentifiers(coreAndPrerelease[1], true)) return false;
  const core = coreAndPrerelease[0].split(".");
  return core.length === 3 && core.every(validNumericIdentifier);
}

const generatedApiModule = "apps/api/src/generated/productVersion.ts";
// These browser workspaces import the shared contract package. Requiring their
// explicit manifest and lockfile mirrors prevents a missing dependency from
// bypassing the product-version authority check through hoisting.
const requiredContractConsumers = new Set([
  "apps/api/package.json",
  "apps/web/package.json",
]);

function assertEqual(actual, expected, label) {
  if (actual !== expected) {
    throw new Error(`${label} is ${JSON.stringify(actual)}; expected ${JSON.stringify(expected)} from VERSION`);
  }
}

export function parseVersionFile(text) {
  if (!text.endsWith("\n") || text.slice(0, -1).includes("\n")) {
    throw new Error("VERSION must contain exactly one SemVer value followed by a newline");
  }
  const version = text.slice(0, -1);
  if (!isStrictSemver(version)) {
    throw new Error(`VERSION must be strict SemVer; received ${JSON.stringify(version)}`);
  }
  return version;
}

export function generatedModule(version) {
  return `// Generated by scripts/check-version-authority.mjs; do not edit.\nexport const PRODUCT_VERSION = ${JSON.stringify(version)} as const;\n`;
}

async function readJson(root, relativePath) {
  try {
    return JSON.parse(await readFile(path.join(root, relativePath), "utf8"));
  } catch (error) {
    throw new Error(`Could not read ${relativePath}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

async function cargoManifestPaths(root) {
  const cratesRoot = path.join(root, "crates");
  const entries = await readdir(cratesRoot, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory() && entry.name.startsWith("dockermap-"))
    .map((entry) => `crates/${entry.name}/Cargo.toml`)
    .sort();
}

async function workspacePackagePaths(root) {
  const rootPackage = await readJson(root, "package.json");
  const workspaceDeclaration = Array.isArray(rootPackage.workspaces)
    ? rootPackage.workspaces
    : rootPackage.workspaces?.packages;
  if (!Array.isArray(workspaceDeclaration)) throw new Error("package.json workspaces must be an array or { packages: string[] }");

  const packagePaths = ["package.json"];
  for (const pattern of workspaceDeclaration) {
    if (typeof pattern !== "string") throw new Error("package.json workspace patterns must be strings");
    const match = pattern.match(/^([^*/]+)\/\*$/);
    if (!match) throw new Error(`Unsupported workspace pattern ${JSON.stringify(pattern)}; version authority requires a single directory wildcard`);
    const workspaceRoot = match[1];
    const entries = await readdir(path.join(root, workspaceRoot), { withFileTypes: true });
    for (const entry of entries.filter((entry) => entry.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
      const relativePath = `${workspaceRoot}/${entry.name}/package.json`;
      try { await readFile(path.join(root, relativePath), "utf8"); } catch { throw new Error(`Workspace ${JSON.stringify(pattern)} contains ${relativePath} without package.json`); }
      packagePaths.push(relativePath);
    }
  }
  return packagePaths;
}

function cargoPackageVersion(manifest, relativePath) {
  const match = manifest.match(/^\[package\][\s\S]*?^version\s*=\s*"([^"]+)"\s*$/m);
  if (!match) throw new Error(`${relativePath} has no [package] version`);
  return match[1];
}

function checkLockfile(lock, version, packagePaths, contractDependencyPaths) {
  assertEqual(lock.version, version, "package-lock.json top-level version");
  const packages = lock.packages;
  if (!packages || typeof packages !== "object") throw new Error("package-lock.json packages is missing");
  for (const relativePath of packagePaths) {
    const packagePath = relativePath === "package.json" ? "" : relativePath.replace(/\/package\.json$/, "");
    const packageEntry = packages[packagePath];
    if (!packageEntry || typeof packageEntry !== "object") throw new Error(`package-lock.json packages[${JSON.stringify(packagePath)}] is missing`);
    assertEqual(packageEntry.version, version, `package-lock.json packages[${JSON.stringify(packagePath)}].version`);
    if (contractDependencyPaths.has(relativePath)) {
      if (!packageEntry.dependencies || typeof packageEntry.dependencies !== "object") {
        throw new Error(`package-lock.json packages[${JSON.stringify(packagePath)}].dependencies is missing`);
      }
      assertEqual(packageEntry.dependencies["@dockermap/contracts"], version, `package-lock.json packages[${JSON.stringify(packagePath)}].dependencies.@dockermap/contracts`);
    }
  }
}

export async function checkVersionAuthority({ root, write = false }) {
  const version = parseVersionFile(await readFile(path.join(root, "VERSION"), "utf8"));
  const packagePaths = await workspacePackagePaths(root);
  for (const consumerPath of requiredContractConsumers) {
    if (!packagePaths.includes(consumerPath)) {
      throw new Error(`Required contracts consumer ${consumerPath} is not declared by the root workspace`);
    }
  }
  const contractDependencyPaths = new Set(requiredContractConsumers);
  for (const relativePath of packagePaths) {
    const packageJson = await readJson(root, relativePath);
    assertEqual(packageJson.version, version, `${relativePath} version`);
    const dependencies = packageJson.dependencies;
    const declaresContracts = dependencies && typeof dependencies === "object" && "@dockermap/contracts" in dependencies;
    if (requiredContractConsumers.has(relativePath) && !declaresContracts) {
      if (!dependencies || typeof dependencies !== "object") {
        throw new Error(`${relativePath} dependencies is missing`);
      }
      throw new Error(`${relativePath} dependency @dockermap/contracts is missing`);
    }
    if (declaresContracts) {
      contractDependencyPaths.add(relativePath);
      assertEqual(dependencies["@dockermap/contracts"], version, `${relativePath} dependency @dockermap/contracts`);
    }
  }
  checkLockfile(await readJson(root, "package-lock.json"), version, packagePaths, contractDependencyPaths);
  for (const relativePath of await cargoManifestPaths(root)) {
    const manifest = await readFile(path.join(root, relativePath), "utf8");
    assertEqual(cargoPackageVersion(manifest, relativePath), version, `${relativePath} version`);
  }

  const generatedPath = path.join(root, generatedApiModule);
  const expectedGenerated = generatedModule(version);
  if (write) {
    await writeFile(generatedPath, expectedGenerated);
  } else {
    let actualGenerated;
    try { actualGenerated = await readFile(generatedPath, "utf8"); } catch { throw new Error(`${generatedApiModule} is missing; run npm run generate:version`); }
    assertEqual(actualGenerated, expectedGenerated, `${generatedApiModule}`);
  }
  return version;
}

async function main() {
  const args = process.argv.slice(2);
  let write = false;
  let root = process.cwd();
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--write") write = true;
    else if (args[index] === "--root") {
      root = args[index + 1];
      if (!root) throw new Error("--root requires a directory");
      index += 1;
    } else throw new Error(`Unknown argument: ${args[index]}`);
  }
  const version = await checkVersionAuthority({ root: path.resolve(root), write });
  process.stdout.write(`${write ? "Generated" : "Checked"} product version ${version}\n`);
}

if (import.meta.url === new URL(process.argv[1], "file:").href) {
  main().catch((error) => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
}
